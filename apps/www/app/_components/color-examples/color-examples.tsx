import {
  type SemanticColorNames,
  semanticColorSpec,
} from '@digdir/designsystemet/internal';
import type { CSSProperties } from 'react';
import { useTranslation } from 'react-i18next';
import { useLoaderData } from 'react-router';
import { ExampleFigure } from '~/_components/example-figure/example-figure';
import type {
  ColorExample,
  SampleColorName,
} from '~/_utils/color-examples.server';
import { specGroups, specSteps } from '~/_utils/color-spec';
import classes from './color-examples.module.css';

type Scheme = Pick<ColorExample, 'light' | 'dark'>;

/**
 * The example color scales, generated by the page loader (at build time when prerendering).
 * See `getColorExamples` in `color-examples.server.ts`.
 */
const useColorExamples = () => {
  const { colorExamples } = useLoaderData() as {
    colorExamples?: ColorExample[];
  };
  if (!colorExamples) {
    throw new Error(
      'Color examples not found. Add `colorExamples: getColorExamples()` to the page loader.',
    );
  }
  return colorExamples;
};

/** Props from MDX are not type-checked, so a typo should fail with a readable message */
function assertSteps(steps: unknown): asserts steps is SemanticColorNames[] {
  const unknown = Array.isArray(steps)
    ? steps.filter((step) => !Object.hasOwn(semanticColorSpec, step))
    : ['(missing `steps` prop)'];
  if (unknown.length) {
    throw new Error(
      `ColorSwatches: unknown color step ${unknown.join(', ')}. Use one of ${Object.keys(semanticColorSpec).join(', ')}.`,
    );
  }
}

/** CSS variables with the light and dark value of a step, used with `light-dark()` in the CSS */
const stepVars = (
  scheme: Scheme,
  property: 'bg' | 'fg' | 'border',
  step: SemanticColorNames,
) => ({
  [`--${property}-light`]: scheme.light[step],
  [`--${property}-dark`]: scheme.dark[step],
});

/** Which colors to show a step with, so it looks the way it is meant to be used */
const getSwatchVars = (
  scheme: Scheme,
  step: SemanticColorNames,
): CSSProperties => {
  switch (semanticColorSpec[step].group) {
    case 'border':
      return {
        ...stepVars(scheme, 'bg', 'surface-tinted'),
        ...stepVars(scheme, 'fg', 'text-default'),
        ...stepVars(scheme, 'border', step),
      };
    case 'text':
      return {
        ...stepVars(scheme, 'bg', 'background-default'),
        ...stepVars(scheme, 'fg', step),
      };
    case 'base':
      return step.startsWith('base-contrast')
        ? {
            ...stepVars(scheme, 'bg', 'base-default'),
            ...stepVars(scheme, 'fg', step),
          }
        : {
            ...stepVars(scheme, 'bg', step),
            ...stepVars(scheme, 'fg', 'base-contrast-default'),
          };
    default:
      return {
        ...stepVars(scheme, 'bg', step),
        ...stepVars(scheme, 'fg', 'text-default'),
      };
  }
};

type ColorSwatchesProps = {
  /** One row per step, showing the step in every example color scale */
  steps: SemanticColorNames[];
  caption?: string;
};

/**
 * Shows color steps in several color scales, generated with the same code as the Theme Builder.
 * Follows the page's light or dark mode.
 */
export const ColorSwatches = ({ steps, caption }: ColorSwatchesProps) => {
  const { t } = useTranslation();
  const sampleScales = useColorExamples();
  assertSteps(steps);

  return (
    <ExampleFigure caption={caption} className={classes.rows}>
      {steps.map((step) => (
        <div key={step} className={classes.row}>
          <code className={classes.rowLabel}>{step}</code>
          <div className={classes.swatches}>
            {sampleScales.map((scheme) => (
              <div
                key={scheme.name}
                className={classes.swatch}
                data-group={semanticColorSpec[step].group}
                style={getSwatchVars(scheme, step)}
              >
                {t(`color-examples.colors.${scheme.name}`)}
              </div>
            ))}
          </div>
        </div>
      ))}
    </ExampleFigure>
  );
};

type ColorScaleOverviewProps = {
  /** One of the example color scales */
  color: SampleColorName;
  caption?: string;
};

/**
 * Shows every step in a color scale, grouped like in the color spec.
 * Follows the page's light or dark mode.
 */
export const ColorScaleOverview = ({
  color,
  caption,
}: ColorScaleOverviewProps) => {
  const sampleScales = useColorExamples();
  const scheme = sampleScales.find(({ name }) => name === color);
  if (!scheme) {
    throw new Error(
      `ColorScaleOverview: unknown color "${color}". Use one of ${sampleScales.map(({ name }) => name).join(', ')}.`,
    );
  }

  return (
    <ExampleFigure caption={caption} className={classes.overview}>
      {specGroups.map((group) => (
        <div key={group} className={classes.group}>
          <div className={classes.groupLabel}>
            {group.charAt(0).toUpperCase() + group.slice(1)}
          </div>
          <div className={classes.groupSteps}>
            {specSteps
              .filter((step) => step.group === group)
              .map(({ name }) => (
                <div key={name} className={classes.step}>
                  <div
                    className={classes.stepColor}
                    style={stepVars(scheme, 'bg', name)}
                  />
                  <span className={classes.stepLabel}>
                    {name.replace(`${group}-`, '')}
                  </span>
                </div>
              ))}
          </div>
        </div>
      ))}
    </ExampleFigure>
  );
};
